// Writes docs/V2_CONTENT_QA.md from src/content. Run: npm run content:report
import { writeFileSync } from "node:fs";
import { flagExists, loadRawContent } from "../src/lib/content/node-content.ts";
import { balanceReport, validateContent } from "../src/lib/content/validate.ts";

const raw = loadRawContent();
const { errors, warnings } = validateContent(raw, { flagExists });
const live = new Set(raw.editions.editions[raw.editions.default].questionIds);
const entities = new Map(raw.entities.map(e => [e.id, e]));
const report = balanceReport(raw, id => live.has(id));
const row = (cells: unknown[]) => "| " + cells.map(c => String(c ?? "").replace(/\|/g, "\\|")).join(" | ") + " |";
const table = (head: string[], rows: unknown[][]) => [row(head), row(head.map(() => "---")), ...rows.map(row)].join("\n");
const shares = (tally: Record<string, { count: number; share: number }>) => table(["Value", "Count", "Share %"], Object.entries(tally).map(([k, v]) => [k, v.count, v.share]));
const host = (url: string) => new URL(url).hostname.replace(/^www\./, "");

// Whole active catalog, counted by person (each entity's first active question gives its category).
function catalogBalance(): string[] {
 const people = new Map<string, { category: string; subcategory: string; region: string; current: boolean }>();
 for (const q of raw.questions) if (q.active && !people.has(q.entityId)) {
  const e = entities.get(q.entityId)!;
  people.set(q.entityId, { category: q.primaryCategory, subcategory: q.primaryCategory + "/" + q.subcategory, region: e.region, current: Boolean(e.tags?.includes("current")) });
 }
 const all = [...people.values()], total = all.length;
 const tally = (key: "category" | "subcategory" | "region") => {
  const counts: Record<string, number> = {};
  for (const p of all) counts[p[key]] = (counts[p[key]] ?? 0) + 1;
  return Object.entries(counts).sort((a, b) => b[1] - a[1]);
 };
 const pct = (n: number, of = total) => Math.round(n / of * 1000) / 10;
 const music = all.filter(p => p.category === "music").length, kpop = all.filter(p => p.subcategory === "music/k-pop").length;
 const topCategory = tally("category")[0], topRegion = tally("region")[0];
 const checks: [string, boolean, string][] = [
  ["Any category > 35% of the pool", pct(topCategory[1]) > 35, `${topCategory[0]} ${pct(topCategory[1])}%`],
  ["Any region > 35%", pct(topRegion[1]) > 35, `${topRegion[0]} ${pct(topRegion[1])}%`],
  ["K-pop > 15% of Music", pct(kpop, music) > 15, `${kpop}/${music} = ${pct(kpop, music)}%`],
  ["Music > 35% overall", pct(music) > 35, `${music}/${total} = ${pct(music)}%`],
 ];
 const t = (rows: [string, number][]) => table(["Value", "People", "Share %"], rows.map(([k, n]) => [k, n, pct(n)]));
 return [
  "## 0. Catalog balance (all active content, by person)",
  `Active people: **${total}**. Tagged younger/current: **${all.filter(p => p.current).length}** (editorial tag \`current\`; legacy entries are untagged).`,
  "",
  "### Warning thresholds (warnings, not failures)",
  table(["Check", "Warning?", "Value"], checks.map(([name, warn, value]) => [name, warn ? "⚠ yes" : "no", value])),
  "### By category", t(tally("category")),
  "### By origin region", t(tally("region")),
  "### By subcategory", t(tally("subcategory")),
 ];
}

const lines = [
 "# StarTap V2 — content QA report",
 "",
 `Generated by \`npm run content:report\` from \`src/content\`. Do not edit by hand.`,
 "",
 `**Validation:** ${errors.length} errors, ${warnings.length} warnings. **Entities:** ${raw.entities.length}. **Questions:** ${raw.questions.length} (${raw.questions.filter(q => q.active).length} active). **Live edition (${raw.editions.default}):** ${live.size}.`,
 ...(errors.length ? ["", "## Errors", ...errors.map(e => "- " + e)] : []),
 "",
 ...catalogBalance(),
 "",
 "## 1. Sources needing replacement",
 "Kept playable. Replace with a primary, authoritative or reputable secondary source, then set `sourceQuality` accordingly.",
 "",
 table(["Question", "Star", "Weak source", "Note"], raw.questions.filter(q => q.sources.some(s => s.quality === "needs_review")).map(q => [
  q.id, entities.get(q.entityId)?.name, q.sources.filter(s => s.quality === "needs_review").map(s => host(s.url)).join(", "), q.review.notes?.join(" ") ?? "",
 ])),
 "",
 "## 2. Image-rights audit",
 "No image is added without a verified licence. Entities without one use the monogram fallback.",
 "",
 table(["Entity", "Status", "Licence", "Source"], raw.entities.map(e => [e.name, e.image.status, e.image.license ?? "—", e.image.source ?? "—"])),
 "",
 `Licensed: ${raw.entities.filter(e => e.image.status === "licensed").length}. Monogram fallback: ${raw.entities.filter(e => e.image.status === "none").length}.`,
 "",
 "## 3. Star Portal coverage",
 `With verified links: ${raw.entities.filter(e => e.portal).length}. Hidden (no links): ${raw.entities.filter(e => !e.portal).length}.`,
 "",
 table(["Entity", "Listen", "Watch", "Discover", "Source name"], raw.entities.map(e => [e.name, e.portal?.listenUrl ? "yes" : "", e.portal?.watchUrl ? "yes" : "", e.portal?.discoverUrl ? "yes" : "", e.portal?.sourceName ?? ""])),
 "",
 "## 4. Provisional classifications (review individually)",
 "Assigned during migration. Answers and wording are unchanged. Difficulty criteria: EASY = globally famous, obvious association, broad clue; MEDIUM = famous but the answer is less obvious; HARD = specific city, event or career knowledge; LEGEND = specialist knowledge or a deliberately challenging clue.",
 "",
 table(["Question", "Live", "Active", "Category", "Subcategory", "Type", "Difficulty", "Origin", "Region", "Answer", "Source quality"], raw.questions.map(q => {
  const e = entities.get(q.entityId)!;
  return [q.id, live.has(q.id) ? "yes" : "", q.active ? "yes" : "no", q.primaryCategory, q.subcategory, q.questionType, q.difficulty, e.countryOfOrigin, e.region, `${q.answer.city}, ${q.answer.countryCode}`, q.sourceQuality];
 })),
 "",
 "## 5. Origin notes",
 ...raw.entities.filter(e => e.originNote).map(e => `- **${e.name}:** ${e.originNote}`),
 "",
 "## 6. Inactive legacy questions",
 "Still served by their original editions. Excluded from future pools because they duplicate a live answer.",
 ...raw.questions.filter(q => !q.active).map(q => `- \`${q.id}\`: ${q.review.notes?.join(" ")}`),
 "",
 "## 7. Balance (live edition)",
 "### By category", shares(report.byCategory),
 "### By subcategory", shares(report.bySubcategory),
 "### By origin region", shares(report.byRegion),
 "### By question type", shares(report.byQuestionType),
 "### By difficulty (provisional)", shares(report.byDifficulty),
 "### By primary source quality", shares(report.bySourceQuality),
 "",
];
writeFileSync(new URL("../docs/V2_CONTENT_QA.md", import.meta.url), lines.join("\n"));
console.log(`V2_CONTENT_QA.md written: ${errors.length} errors, ${warnings.length} warnings`);
if (errors.length) process.exitCode = 1;
