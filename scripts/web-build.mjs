// Static export for https://startap.fun → out/. Run: npm run build:web
// After the build it adds an Apache/LiteSpeed .htaccess (404 page, MIME types the map needs, long-lived caching
// for hashed assets) and scans the output for anything that must never ship: localhost URLs, local disk paths,
// development endpoints. A failed scan fails the build.
import { spawnSync } from "node:child_process";
import { copyFileSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { stripInternal } from "./internal-files.mjs";

const OUT = "out";
const result = spawnSync(process.execPath, ["node_modules/next/dist/bin/next", "build"], { stdio: "inherit", env: { ...process.env, STARTAP_WEB: "1" } });
if (result.status !== 0) process.exit(result.status ?? 1);

// Internal provenance notes kept beside the media in public/ (source logs, artwork notes) are for the project, not the
// public site; the shared rule in internal-files.mjs removes them from the output. Font licences are kept.
const removed = stripInternal(OUT);
console.log(`internal notes excluded: ${removed.join(", ") || "none"}`);

// Next 16 writes each route's prefetch segments as nested folders (play/__next.category/$d$slug/__PAGE__.txt) but the
// client requests them by flat dotted name (play/__next.category.$d$slug.__PAGE__.txt), which a plain static host
// cannot map — every link prefetch would 404. Write a flat copy beside each nested one.
let flattened = 0;
const flatten = dir => { for (const name of readdirSync(dir)) {
 const p = join(dir, name);
 if (!statSync(p).isDirectory()) continue;
 if (name.startsWith("__next.")) for (const file of walkFiles(p)) {
  const flat = join(dir, [name, ...relative(p, file).split(/[\\/]/)].join("."));
  copyFileSync(file, flat); flattened++;
 } else flatten(p);
} };
const walkFiles = dir => readdirSync(dir).flatMap(n => { const p = join(dir, n); return statSync(p).isDirectory() ? walkFiles(p) : [p]; });
flatten(OUT);
console.log(`prefetch segments: ${flattened} flat copies written`);

writeFileSync(join(OUT, ".htaccess"), `# StarTap static site (generated by scripts/web-build.mjs)
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_mime.c>
  # The map's worker is an ES module: browsers refuse to run it unless it is served as JavaScript.
  AddType text/javascript .mjs
  AddType application/geo+json .geojson
  AddType application/x-protobuf .pbf
  AddType application/manifest+json .webmanifest
  AddType video/mp4 .mp4
  AddType image/webp .webp
</IfModule>

<IfModule mod_headers.c>
  # Content-hashed build files never change; everything else (pages, data, media) revalidates.
  <If "%{REQUEST_URI} =~ m#^/_next/static/#">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </If>
  <Else>
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </Else>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
</IfModule>
`);

// Output scan
const walk = dir => readdirSync(dir).flatMap(name => { const p = join(dir, name); return statSync(p).isDirectory() ? walk(p) : [p]; });
const TEXT = /\.(html|js|mjs|css|json|txt|xml|webmanifest|geojson|htaccess)$|\.htaccess$/;
const RULES = [
 ["localhost URL", /https?:\/\/(localhost|127\.0\.0\.1|0\.0\.0\.0)(:\d+)?\//g],
 ["Windows disk path", /[A-Z]:\\\\?(Users|Projects)\\/g],
 ["development server", /webpack-hmr|__nextjs_original-stack-frame|_next\/webpack-hmr/g],
];
const problems = [];
let bytes = 0, files = 0;
for (const file of walk(OUT)) {
 if (/SOURCES\.txt$|\.md$/i.test(file)) problems.push(`${relative(OUT, file)}: internal note shipped`);
 files++; bytes += statSync(file).size;
 if (!TEXT.test(file)) continue;
 const text = readFileSync(file, "utf8");
 for (const [label, re] of RULES) for (const m of text.matchAll(re)) problems.push(`${relative(OUT, file)}: ${label} → ${m[0]}`);
}
for (const route of ["index.html", "play/index.html", "privacy/index.html", "terms/index.html", "support/index.html", "how-to-play/index.html", "404.html", "manifest.webmanifest", "robots.txt", "sitemap.xml"])
 try { statSync(join(OUT, route)); } catch { problems.push(`missing ${route}`); }
console.log(`\nweb export: ${OUT}/ · ${files} files · ${(bytes / 1048576).toFixed(1)} MB`);
if (problems.length) { console.error("Output scan FAILED:\n " + problems.join("\n ")); process.exit(1); }
console.log("Output scan passed: no localhost URLs, local paths or development endpoints; all public routes present.");
